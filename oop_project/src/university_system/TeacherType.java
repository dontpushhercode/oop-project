package university_system;
/**
 * Represents academic ranks of teachers.
 */
public enum TeacherType {
	
	/**
     * Assistant teacher rank.
     */
    ASSISTANT,
    
    /**
     * Tutor rank.
     */
    TUTOR,
    
    /**
     * Lecturer rank.
     */
    LECTURER,
    
    /**
     * Senior lecturer rank.
     */
    SENIOR_LECTURER,
    
    /**
     * Professor rank.
     */
    PROFESSOR
}