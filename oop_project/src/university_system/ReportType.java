package university_system;
/**
 * Represents the type of report generated in the university system.
 */
public enum ReportType {
	
	/**
     * Report containing student enrollment information.
     */
    ENROLLMENT,
    
    /**
     * Report containing academic performance information
     * about students.
     */
    ACADEMIC_PERFORMANCE,
    
    /**
     * Report containing course performance statistics
     * and analysis.
     */
    COURSE_PERFORMANCE
}