package university_system;
/**
 * Represents the type of lesson conducted in a course section.
 */
public enum LessonType {
	
	/**
     * Lecture-based lesson focused on theoretical material.
     */
    LECTURE,
    
    /**
     * Practical lesson focused on exercises and problem solving.
     */
    PRACTICE,
    
    /**
     * Laboratory lesson focused on hands-on work and experiments.
     */
    LABORATORY
}