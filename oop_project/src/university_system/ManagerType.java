package university_system;
/**
 * Represents the type of manager in the university system.
 */
public enum ManagerType {
	
	/**
     * Office registration manager responsible for enrollment
     * and registration processes.
     */
    OR,
    
    /**
     * Academic manager responsible for academic affairs.
     */
    ACADEMIC,
    
    /**
     * Administrative manager responsible for administrative operations.
     */
    ADMINISTRATIVE,
    
    /**
     * Department manager responsible for department management.
     */
    DEPARTMENT
}